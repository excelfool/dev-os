// Runs as `prebuild`, so it executes inside `npm run build` — which is where
// Netlify's COMMIT_REF exists. It is a BUILD-time variable and is absent from
// the function's runtime environment, so reading process.env at request time
// reported "dev" on the live site while passing locally, where `next dev`
// compiles and serves in one process and the two are indistinguishable.
//
// Writes src/generated/build-info.ts. The checked-in default says "dev", and
// with no commit variable set the script writes the same content, so local
// builds leave git untouched.
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const out = process.argv.includes('--out')
  ? process.argv[process.argv.indexOf('--out') + 1]
  : resolve(process.cwd(), 'src/generated/build-info.ts');

const commit = process.env.COMMIT_REF ?? process.env.COMMIT_SHA ?? 'dev';
if (!/^[A-Za-z0-9._-]{1,64}$/.test(commit)) {
  throw new Error(`Refusing to embed a commit identifier that is not a plain token: ${JSON.stringify(commit)}`);
}

writeFileSync(
  out,
  `// Generated by scripts/write-build-info.mjs at build time. Do not edit.\n` +
    `export const BUILD_COMMIT = ${JSON.stringify(commit)};\n`,
);
console.log(`build-info: commit=${commit} -> ${out}`);
